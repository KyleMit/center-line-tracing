"""Synthetic ground-truth corpus (Common Setup §"Build the synthetic corpus first",
report §12.1).

Each case is generated BY STROKING A KNOWN CENTERLINE, so we can measure true
centerline error rather than only reconstruction error. Writes, per case:

    debug/native-geometry/synthetic/<id>-<name>.svg    filled shape (input)
    debug/native-geometry/synthetic/<id>-<name>.json   ground-truth centerline(s)

The 20 cases follow the Common Setup list in order.
"""

from __future__ import annotations

import json
import math
import os

from shapely.geometry import LineString, Point, MultiPolygon, Polygon
from shapely.ops import unary_union

W, H = 400, 300
R = 8.0  # stroke radius (16px stroke)

CAP = {"round": 1, "butt": 2, "square": 3}
JOIN = {"round": 1, "mitre": 2, "bevel": 3}


def stroke(pts, r=R, cap="round", join="round", resolution=32):
    return LineString(pts).buffer(
        r, cap_style=CAP[cap], join_style=JOIN[join], resolution=resolution
    )


def arc(cx, cy, rad, a0, a1, n=64):
    return [
        (cx + rad * math.cos(a0 + (a1 - a0) * i / n), cy + rad * math.sin(a0 + (a1 - a0) * i / n))
        for i in range(n + 1)
    ]


def bezier(p0, p1, p2, p3, n=64):
    out = []
    for i in range(n + 1):
        t = i / n
        u = 1 - t
        x = u**3 * p0[0] + 3 * u * u * t * p1[0] + 3 * u * t * t * p2[0] + t**3 * p3[0]
        y = u**3 * p0[1] + 3 * u * u * t * p1[1] + 3 * u * t * t * p2[1] + t**3 * p3[1]
        out.append((x, y))
    return out


def _cases():
    c = []
    c.append(("01", "horizontal-line", [[(60, 150), (340, 150)]], dict()))
    c.append(("02", "diagonal-line", [[(60, 240), (340, 60)]], dict()))
    c.append(("03", "circular-arc", [arc(200, 210, 120, math.pi, 2 * math.pi)], dict()))
    c.append(("04", "s-curve", [bezier((60, 240), (160, 60), (240, 240), (340, 60))], dict()))
    c.append(
        ("05", "tight-u", [[(120, 60)] + arc(200, 200, 80, math.pi, 2 * math.pi)[::-1] + [(280, 60)]], dict())
    )
    c.append(("06", "closed-loop", [arc(200, 150, 100, 0, 2 * math.pi)], dict()))
    c.append(("07", "round-cap", [[(120, 150), (280, 150)]], dict(cap="round")))
    c.append(("08", "butt-cap", [[(120, 150), (280, 150)]], dict(cap="butt")))
    c.append(("09", "square-cap", [[(120, 150), (280, 150)]], dict(cap="square")))
    c.append(("10", "round-join", [[(80, 240), (200, 80), (320, 240)]], dict(join="round")))
    c.append(("11", "bevel-join", [[(80, 240), (200, 80), (320, 240)]], dict(join="bevel")))
    c.append(("12", "miter-join", [[(80, 240), (200, 80), (320, 240)]], dict(join="mitre")))
    c.append(("13", "x-crossing-separate", [[(80, 80), (320, 220)], [(80, 220), (320, 80)]], dict(merge=False)))
    c.append(("14", "x-crossing-union", [[(80, 80), (320, 220)], [(80, 220), (320, 80)]], dict(merge=True)))
    c.append(("15", "t-junction", [[(80, 100), (320, 100)], [(200, 100), (200, 260)]], dict(merge=True)))
    c.append(
        ("16", "y-junction", [[(200, 260), (200, 160)], [(200, 160), (110, 60)], [(200, 160), (290, 60)]], dict(merge=True))
    )
    c.append(("17", "parallel-close", [[(60, 130), (340, 130)], [(60, 170), (340, 170)]], dict(merge=False)))
    c.append(("18", "self-overlap", [bezier((100, 200), (330, 60), (70, 60), (300, 200))], dict()))
    c.append(("19", "variable-width", [[(60, 150), (340, 150)]], dict(variable=True)))
    c.append(("20", "noisy-boundary", [bezier((60, 220), (160, 60), (240, 240), (340, 80))], dict(noise=0.9)))
    return c


def build(case):
    cid, name, paths, opts = case
    cap = opts.get("cap", "round")
    join = opts.get("join", "round")

    if opts.get("variable"):
        # union of discs with linearly varying radius — a true variable-width stroke
        pts = paths[0]
        line = LineString(pts)
        discs = []
        n = 400
        for i in range(n + 1):
            p = line.interpolate(i / n, normalized=True)
            r = 4.0 + 10.0 * (i / n)
            discs.append(Point(p.x, p.y).buffer(r, resolution=16))
        geom = unary_union(discs)
        polys = [geom] if isinstance(geom, Polygon) else list(geom.geoms)
        return polys, paths

    strokes = [stroke(p, cap=cap, join=join) for p in paths]

    if opts.get("noise"):
        amp = opts["noise"]
        out = []
        for s in strokes:
            ring = list(s.exterior.coords)
            jit = []
            for i, (x, y) in enumerate(ring[:-1]):
                # deterministic pseudo-noise (no RNG seed dependence)
                d = amp * math.sin(i * 2.399963) * math.cos(i * 0.7891)
                cx, cy = s.centroid.x, s.centroid.y
                vx, vy = x - cx, y - cy
                m = math.hypot(vx, vy) or 1.0
                jit.append((x + d * vx / m, y + d * vy / m))
            jit.append(jit[0])
            p = Polygon(jit)
            out.append(p if p.is_valid else p.buffer(0))
        strokes = out

    if opts.get("merge") is True or (len(strokes) > 1 and opts.get("merge") is None):
        geom = unary_union(strokes)
        polys = [geom] if isinstance(geom, Polygon) else list(geom.geoms)
    else:
        polys = []
        for s in strokes:
            polys.extend([s] if isinstance(s, Polygon) else list(s.geoms))
    return polys, paths


def poly_to_d(poly):
    def ring(coords):
        pts = list(coords)
        d = f"M {pts[0][0]:.4f} {pts[0][1]:.4f} " + " ".join(
            f"L {x:.4f} {y:.4f}" for x, y in pts[1:-1]
        )
        return d + " Z"

    return " ".join([ring(poly.exterior.coords)] + [ring(r.coords) for r in poly.interiors])


def write_svg(path, polys, w=W, h=H):
    body = "\n".join(
        f'  <path d="{poly_to_d(p)}" fill="#000000" fill-rule="evenodd"/>' for p in polys
    )
    svg = (
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{w}" height="{h}" '
        f'viewBox="0 0 {w} {h}">\n{body}\n</svg>\n'
    )
    with open(path, "w") as f:
        f.write(svg)


def main(outdir):
    os.makedirs(outdir, exist_ok=True)
    index = []
    for case in _cases():
        cid, name, paths, opts = case
        polys, gt = build(case)
        base = f"{cid}-{name}"
        write_svg(os.path.join(outdir, base + ".svg"), polys)
        meta = {
            "id": cid,
            "name": name,
            "radius": R,
            "cap": opts.get("cap", "round"),
            "join": opts.get("join", "round"),
            "variable_width": bool(opts.get("variable")),
            "boundary_noise": opts.get("noise", 0.0),
            "centerlines": [[[round(x, 4), round(y, 4)] for x, y in p] for p in gt],
        }
        with open(os.path.join(outdir, base + ".json"), "w") as f:
            json.dump(meta, f)
        index.append(base)
        print(f"{base}: {len(polys)} polygon(s)")
    with open(os.path.join(outdir, "index.json"), "w") as f:
        json.dump(index, f, indent=1)


if __name__ == "__main__":
    import sys

    main(sys.argv[1] if len(sys.argv) > 1 else "debug/native-geometry/synthetic")
