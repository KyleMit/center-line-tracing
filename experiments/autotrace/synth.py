#!/usr/bin/env python3
"""Synthetic ground-truth corpus (Common Setup / report §12.1).

Each case is generated BY STROKING A KNOWN CENTERLINE, so unlike the real
artwork we can measure true centerline error rather than only reconstruction
error, and say exactly which geometric feature breaks the backend.

Raster note: cases 13 ("X kept as separate shapes") and 14 ("X boolean-unioned")
are the same pixels once rasterised.  For a raster backend the meaningful
distinction is whether the two strokes are traced as two masks or one, so that
is what is implemented -- and the gap between the two rows is a direct measure
of how much source-element separation is worth to this backend.
"""

from __future__ import annotations

import argparse
import json
import math
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent))

import atrace  # noqa: E402
import width as W  # noqa: E402
from svgio import SVG_NS, Renderer  # noqa: E402

REPO = Path(__file__).resolve().parent.parent.parent
DEBUG = REPO / "debug" / "autotrace"
SCRATCH = Path("/tmp/claude-0/-home-user-center-line-tracing/"
               "06888930-c1d3-5025-96f2-3d47c53efe6c/scratchpad/autotrace-synth")

W_DEF = 20.0  # stroke width in user units
BOX = (0.0, 0.0, 300.0, 200.0)


def _poly(fn, t0, t1, n=400):
    ts = np.linspace(t0, t1, n)
    return np.array([fn(t) for t in ts])


def _line(p0, p1, n=200):
    p0, p1 = np.array(p0, float), np.array(p1, float)
    return np.array([p0 + (p1 - p0) * t for t in np.linspace(0, 1, n)])


def _d(pts):
    return "M " + " L ".join(f"{x:.4f} {y:.4f}" for x, y in pts)


def cases():
    """(name, [ (centerline_pts, stroke_width, cap, join) ], separate_masks)."""
    C = []
    A = lambda pts, w=W_DEF, cap="round", join="round": (pts, w, cap, join)

    C.append(("01-horizontal-line", [A(_line((50, 100), (250, 100)))], False))
    C.append(("02-diagonal-line", [A(_line((50, 40), (250, 160)))], False))
    C.append(("03-circular-arc", [A(_poly(
        lambda t: (150 + 90 * math.cos(t), 150 - 90 * math.sin(t)), 0.15, math.pi - 0.15))], False))
    C.append(("04-s-curve", [A(_poly(
        lambda t: (50 + 200 * t, 100 + 55 * math.sin(2 * math.pi * t)), 0, 1))], False))
    C.append(("05-tight-u", [A(np.vstack([
        _line((100, 40), (100, 110), 120),
        _poly(lambda a: (130 + 30 * math.cos(a), 110 + 30 * math.sin(a)), math.pi, math.pi / 2, 80),
        _poly(lambda a: (130 + 30 * math.cos(a), 110 + 30 * math.sin(a)), math.pi / 2, 0, 80),
        _line((160, 110), (160, 40), 120),
    ]))], False))
    loop = _poly(lambda t: (150 + 80 * math.cos(t), 100 + 60 * math.sin(t)), 0, 2 * math.pi)
    C.append(("06-closed-loop", [A(loop)], False))
    C.append(("07-round-cap", [A(_line((60, 100), (240, 100)), cap="round")], False))
    C.append(("08-butt-cap", [A(_line((60, 100), (240, 100)), cap="butt")], False))
    C.append(("09-square-cap", [A(_line((60, 100), (240, 100)), cap="square")], False))
    corner = np.vstack([_line((60, 40), (150, 130), 200), _line((150, 130), (240, 40), 200)])
    C.append(("10-round-join", [A(corner, join="round")], False))
    C.append(("11-bevel-join", [A(corner, join="bevel")], False))
    acute = np.vstack([_line((60, 40), (150, 140), 200), _line((150, 140), (230, 45), 200)])
    C.append(("12-miter-join", [A(acute, join="miter")], False))
    xa = _line((60, 40), (240, 160))
    xb = _line((60, 160), (240, 40))
    C.append(("13-x-crossing-separate", [A(xa), A(xb)], True))
    C.append(("14-x-crossing-unioned", [A(xa), A(xb)], False))
    C.append(("15-t-junction", [A(_line((60, 60), (240, 60))), A(_line((150, 60), (150, 170)))], False))
    C.append(("16-y-junction", [
        A(_line((150, 170), (150, 110))), A(_line((150, 110), (70, 40))),
        A(_line((150, 110), (230, 40)))], False))
    gap = W_DEF * 1.35
    C.append(("17-near-parallel", [
        A(_line((50, 100 - gap / 2), (250, 100 - gap / 2))),
        A(_line((50, 100 + gap / 2), (250, 100 + gap / 2)))], False))
    C.append(("18-self-overlap", [A(np.vstack([
        _line((60, 100), (200, 100), 200),
        _poly(lambda a: (200 + 26 * math.cos(a), 74 + 26 * math.sin(a)),
              math.pi / 2, -math.pi / 2, 160),
        _line((200, 48), (120, 48), 160),
    ]))], False))
    # variable width: emitted as a stack of segments with a linear width ramp
    seg = _line((50, 100), (250, 100), 40)
    var = [(seg[i:i + 2], 8 + 22 * (i / 38.0), "round", "round") for i in range(39)]
    C.append(("19-variable-width", var, False))
    rng = np.random.default_rng(7)
    noisy = _line((50, 100), (250, 100), 220)
    noisy = noisy + np.column_stack([np.zeros(len(noisy)), rng.normal(0, 0.9, len(noisy))])
    C.append(("20-noisy-boundary", [A(noisy)], False))
    return C


def svg_for(strokes):
    parts = [f'<svg xmlns="{SVG_NS}" viewBox="{BOX[0]} {BOX[1]} {BOX[2]} {BOX[3]}" '
             f'width="{BOX[2]}" height="{BOX[3]}">']
    for pts, w, cap, join in strokes:
        parts.append(
            f'<path d="{_d(pts)}" fill="none" stroke="#000000" stroke-width="{w}" '
            f'stroke-linecap="{cap}" stroke-linejoin="{join}"/>')
    parts.append("</svg>")
    return "".join(parts)


def centerline_error(traced_px, gt_px):
    """Symmetric nearest-point distance, in pixels. Median and P95 (never max)."""
    if len(traced_px) == 0 or len(gt_px) == 0:
        return {"median": float("nan"), "p95": float("nan")}
    from scipy.spatial import cKDTree
    ta, tb = cKDTree(traced_px), cKDTree(gt_px)
    d1, _ = tb.query(traced_px)   # traced -> gt  (spurious branches show up here)
    d2, _ = ta.query(gt_px)       # gt -> traced  (missed sections show up here)
    return {
        "median": float(np.median(np.concatenate([d1, d2]))),
        "p95": float(np.percentile(np.concatenate([d1, d2]), 95)),
        "traced_to_gt_p95": float(np.percentile(d1, 95)),
        "gt_to_traced_p95": float(np.percentile(d2, 95)),
    }


def run(scale=4.0, cap_extend=True, stat="trimmed", params=None):
    params = params or atrace.TraceParams()
    SCRATCH.mkdir(parents=True, exist_ok=True)
    r = Renderer(SCRATCH)
    rows = []
    try:
        for name, strokes, separate in cases():
            groups = [[s] for s in strokes] if separate else [strokes]
            traced_all, radii, n_sub, n_out, n_closed = [], [], 0, 0, 0
            for gi, grp in enumerate(groups):
                mask, frame = r.mask(svg_for(grp), BOX, scale)
                dist = W.edt(mask)
                sps, _, _ = atrace.run(mask, SCRATCH / "at", params, stem=f"{name}_{gi}")
                W.measure(sps, mask, dist, stat)
                if cap_extend:
                    import pipeline
                    for sp in sps:
                        pipeline._cap_extend(sp, mask, dist, sp.stats.get("radius_px", 0))
                    W.measure(sps, mask, dist, stat)
                n_sub += len(sps)
                for sp in sps:
                    n_out += int(sp.outline_like)
                    n_closed += int(sp.is_closed())
                    radii.append(sp.stats.get("radius_px", 0))
                    traced_all.append(sp.points())
            gt = np.vstack([s[0] for s in strokes]) * scale
            traced = np.vstack(traced_all) if traced_all else np.zeros((0, 2))
            err = centerline_error(traced, gt)
            # Endpoint error is measured separately: free ends are a handful of
            # points, so the whole-path statistic all but hides cap defects --
            # and caps are exactly where a medial axis is known to fall short.
            gt_ends = np.array([p for s in strokes for p in (s[0][0], s[0][-1])]) * scale
            tr_ends = np.array([p for a in traced_all for p in (a[0], a[-1])]) \
                if traced_all else np.zeros((0, 2))
            if len(tr_ends) and len(gt_ends):
                from scipy.spatial import cKDTree
                d, _ = cKDTree(tr_ends).query(gt_ends)
                endpoint_med = float(np.median(d)) / scale
                endpoint_max = float(np.max(d)) / scale
            else:
                endpoint_med = endpoint_max = float("nan")
            true_r = float(np.mean([s[1] for s in strokes])) / 2.0
            got_r = float(np.median(radii)) / scale if radii else 0.0
            rows.append({
                "case": name,
                "n_expected_strokes": len(strokes) if name != "19-variable-width" else 1,
                "n_traced_subpaths": n_sub,
                "n_outline_like": n_out,
                "n_closed": n_closed,
                "centerline_median_px": round(err["median"], 3),
                "centerline_p95_px": round(err["p95"], 3),
                "spurious_p95_px": round(err["traced_to_gt_p95"], 3),
                "missed_p95_px": round(err["gt_to_traced_p95"], 3),
                "centerline_median_user": round(err["median"] / scale, 3),
                "centerline_p95_user": round(err["p95"] / scale, 3),
                "endpoint_median_user": round(endpoint_med, 3),
                "endpoint_max_user": round(endpoint_max, 3),
                "true_radius_user": round(true_r, 3),
                "recovered_radius_user": round(got_r, 3),
                "radius_err_pct": round(100 * (got_r - true_r) / true_r, 2) if true_r else None,
            })
            print(f"{name:26s} sub {n_sub:3d}  cl_med {err['median']/scale:6.2f}u  "
                  f"cl_p95 {err['p95']/scale:6.2f}u  end {endpoint_med:5.2f}u  "
                  f"r {got_r:5.2f}/{true_r:5.2f}u "
                  f"({rows[-1]['radius_err_pct']:+.1f}%)", flush=True)
    finally:
        r.close()
    return rows


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--scale", type=float, default=4.0)
    ap.add_argument("--stat", default="trimmed")
    ap.add_argument("--no-cap-extend", action="store_true")
    ap.add_argument("--out", default=str(DEBUG / "synthetic.json"))
    ap.add_argument("--label", default="s4")
    a = ap.parse_args()
    rows = run(a.scale, not a.no_cap_extend, a.stat)
    p = Path(a.out)
    p.parent.mkdir(parents=True, exist_ok=True)
    store = json.loads(p.read_text()) if p.exists() else {}
    store[a.label] = {"scale": a.scale, "stat": a.stat,
                      "cap_extend": not a.no_cap_extend, "rows": rows}
    p.write_text(json.dumps(store, indent=1))
    print("->", p)


if __name__ == "__main__":
    main()
